import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import converter from 'swagger2openapi';

const root = fileURLToPath(new URL('../', import.meta.url));
const verbs = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];
const sha = (value) => createHash('sha256').update(value).digest('hex');
const rustString = (value) => JSON.stringify(value);
const rustName = (id) => id.replace(/(^|[^a-zA-Z0-9]+)([a-zA-Z0-9])/g, (_, _sep, char) => char.toUpperCase());

// No external resolution: generation is entirely from the copied input.
function localReferences(value) {
  if (!value || typeof value !== 'object') return;
  if (typeof value.$ref === 'string' && !value.$ref.startsWith('#/')) {
    throw new Error(`External reference refused: ${value.$ref}`);
  }
  for (const child of Object.values(value)) localReferences(child);
}

export function operations(openapi) {
  if (!/^3\.0\./.test(openapi.openapi ?? '')) throw new Error('OpenAPI 3.0 input required');
  localReferences(openapi);
  const result = [];
  const ids = new Set();
  const names = new Set();
  for (const [route, item] of Object.entries(openapi.paths ?? {})) {
    if (!route.startsWith('/') || route.includes('?') || route.includes('#')) {
      throw new Error(`Invalid gateway-relative route: ${route}`);
    }
    for (const verb of verbs) {
      const operation = item[verb];
      if (!operation) continue;
      const id = operation.operationId;
      if (!id || !/^[a-zA-Z][a-zA-Z0-9_]*$/.test(id)) throw new Error(`Invalid operationId: ${id}`);
      if (ids.has(id)) throw new Error(`Duplicate operationId: ${id}`);
      ids.add(id);
      if (verb === 'options') continue;
      const name = rustName(id);
      if (names.has(name)) throw new Error(`Rust operation-name collision: ${name}`);
      names.add(name);
      const placeholders = [...route.matchAll(/\{([^{}]+)\}/g)].map((match) => match[1]);
      if (new Set(placeholders).size !== placeholders.length || /[{}]/.test(route.replace(/\{[^{}]+\}/g, ''))) {
        throw new Error(`Malformed path template: ${route}`);
      }
      const parameters = new Map();
      for (const parameter of [...(item.parameters ?? []), ...(operation.parameters ?? [])]) {
        if (parameter.$ref) throw new Error(`Referenced parameter requires explicit supported expansion: ${id}`);
        if (!['path', 'query', 'header', 'cookie'].includes(parameter.in)) {
          throw new Error(`Unsupported parameter location: ${id}/${parameter.in}`);
        }
        parameters.set(`${parameter.in}:${parameter.name}`, parameter);
      }
      const pathParameters = [...parameters.values()].filter((p) => p.in === 'path');
      if (pathParameters.some((p) => !p.required || !placeholders.includes(p.name))
          || placeholders.some((p) => !pathParameters.some((declared) => declared.name === p))) {
        throw new Error(`Path parameter declaration mismatch: ${id}`);
      }
      result.push({ id, name, verb, route, placeholders, parameters: [...parameters.values()], operation });
    }
  }
  if (!result.length) throw new Error('No gateway operations declared');
  return result;
}

export function rust(openapi, sourceDigest) {
  const ops = operations(openapi);
  const lines = [
    '// @generated by scripts/generate.mjs; do not edit.',
    `// Copied Swagger SHA-256: ${sourceDigest}`,
    '// Bodies and replies without complete schemas remain with their typed application owners.',
    '',
    'use super::{Descriptor, Location, Method, Parameter, PlanError, RoutePlan};',
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]',
    '#[repr(u16)]',
    'pub enum Operation {',
    ...ops.map((op) => `    ${op.name},`),
    '}',
    '',
    '#[rustfmt::skip]',
    'impl Operation {',
    `    pub const ALL: &'static [Self] = &[${ops.map((op) => `Self::${op.name}`).join(', ')}];`,
    '',
    "    pub const fn descriptor(self) -> &'static Descriptor { &DESCRIPTORS[self as usize] }",
    '    pub const fn method(self) -> Method { self.descriptor().method }',
    "    pub const fn path_template(self) -> &'static str { self.descriptor().path_template }",
    "    pub const fn operation_id(self) -> &'static str { self.descriptor().operation_id }",
    '',
    '    pub fn from_id(id: &str) -> Option<Self> {',
    '        match id {',
    ...ops.map((op) => `            ${rustString(op.id)} => Some(Self::${op.name}),`),
    '            _ => None,',
    '        }',
    '    }',
    '',
    '    pub fn plan(self, parameters: &[(&str, &str)]) -> Result<RoutePlan, PlanError> {',
    '        super::plan(self, parameters)',
    '    }',
    '}',
    '',
    '#[rustfmt::skip]',
    `const DESCRIPTORS: [Descriptor; ${ops.length}] = [`,
  ];
  for (const op of ops) {
    const contentHasSchema = (content) => Object.values(content ?? {}).some((media) => media.schema !== undefined);
    const parameters = op.parameters.map((p) => `Parameter { name: ${rustString(p.name)}, location: Location::${rustName(p.in)}, required: ${Boolean(p.required)}, schema_type: ${typeof p.schema?.type === 'string' ? `Some(${rustString(p.schema.type)})` : 'None'} }`);
    lines.push('    Descriptor {',
      `        operation_id: ${rustString(op.id)},`,
      `        method: Method::${rustName(op.verb)},`,
      `        path_template: ${rustString(op.route)},`,
      `        path_parameters: &[${op.placeholders.map(rustString).join(', ')}],`,
      `        parameters: &[${parameters.join(', ')}],`,
      `        has_request_schema: ${contentHasSchema(op.operation.requestBody?.content)},`,
      `        has_response_schema: ${Object.values(op.operation.responses ?? {}).some((response) => contentHasSchema(response.content))},`,
      '    },');
  }
  lines.push('];', '');
  return lines.join('\n');
}

export async function artifacts(source) {
  const converted = await converter.convertStr(source.toString('utf8'), {
    targetVersion: '3.0.3', patch: false, warnOnly: false, resolve: false,
  });
  const openapi = converted.openapi;
  const ops = operations(openapi);
  const openapiBytes = `${JSON.stringify(openapi, null, 2)}\n`;
  const generated = rust(openapi, sha(source));
  const provenance = {
    source_sha256: sha(source),
    openapi_sha256: sha(openapiBytes),
    generated_rust_sha256: sha(generated),
    generator_sha256: sha(await fs.readFile(fileURLToPath(import.meta.url))),
    converter: 'swagger2openapi@7.0.8',
    openapi: openapi.openapi,
    paths: Object.keys(openapi.paths).length,
    operations: ops.length,
    cors_operations: Object.values(openapi.paths).filter((item) => item.options).length,
    operations_with_response_schema: ops.filter((op) => Object.values(op.operation.responses ?? {}).some((r) => Object.values(r.content ?? {}).some((media) => media.schema !== undefined))).length,
  };
  return new Map([
    ['spec/gateway-openapi.json', openapiBytes],
    ['spec/provenance.json', `${JSON.stringify(provenance, null, 2)}\n`],
    ['src/generated.rs', generated],
  ]);
}

export async function main(args) {
  const check = args.includes('--check');
  const copyIndex = args.indexOf('--copy-from');
  if (!(args.length === 0
      || (args.length === 1 && args[0] === '--check')
      || (args.length === 2 && args[0] === '--copy-from' && args[1] && !args[1].startsWith('--')))) {
    throw new Error('Usage: generate.mjs [--check | --copy-from <Swagger YAML>]');
  }
  const copied = path.join(root, 'spec/gateway-swagger.yaml');
  const source = await fs.readFile(copyIndex >= 0 ? path.resolve(args[copyIndex + 1]) : copied);
  const outputs = await artifacts(source);
  if (copyIndex >= 0) await fs.writeFile(copied, source);
  for (const [relative, contents] of outputs) {
    const target = path.join(root, relative);
    if (check) {
      if (await fs.readFile(target, 'utf8') !== contents) throw new Error(`Generated output is stale: ${relative}`);
    } else {
      await fs.writeFile(target, contents);
    }
  }
  return outputs;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main(process.argv.slice(2)).then(() => {
    process.stdout.write('Gateway OpenAPI conversion and generated route client are current.\n');
  }).catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
